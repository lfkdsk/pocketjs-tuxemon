import type { TuxLinkConfig } from "./tux-link-config.ts";

const PORTABLE_IMPORT = 'from "./ui/title-battle.tsx";';
const WEB_IMPORT = 'from "./ui/tux-link/title-battle-web.tsx";';

/**
 * Produce the Web-only app entry without changing the portable module graph.
 * Keeping the source as a checked transformation of main.tsx means desktop
 * and PSP continue to compile the original entry byte-for-byte, while Web can
 * replace exactly one composition seam.
 */
export function tuxLinkWebEntrySource(
  portableSource: string,
  config: TuxLinkConfig | null,
): string {
  const first = portableSource.indexOf(PORTABLE_IMPORT);
  if (first < 0 || portableSource.indexOf(PORTABLE_IMPORT, first + 1) >= 0) {
    throw new Error("Tux Link Web entry: expected exactly one title overlay import in main.tsx");
  }
  const prelude = [
    "// Generated by tools/web.ts; do not edit or commit.",
    `globalThis.__pocketTuxLinkBuildConfig = ${JSON.stringify(config)};`,
    "",
    "",
  ].join("\n");
  return prelude + portableSource.replace(PORTABLE_IMPORT, WEB_IMPORT);
}
